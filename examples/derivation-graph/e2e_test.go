// Package derivationgraph provides the end-to-end demo for the derivation graph.
//
// This test drives the full Provenant CLI sequence for computing Operating Income
// from three synthetic accounting datasets (revenue, COGS, OpEx) and asserts:
//
//   - The produced bundle bytes are bit-identical to the committed golden.
//   - The trace of the operating_income token decomposes into all leaf contributions.
//   - The sum of leaf contributions equals the operating_income value.
//   - bundle.Verify and bundle.Replay succeed.
//   - Running the demo twice produces identical bundle bytes (determinism).
//
// Dataset summary (seed 42, generated by gen/gen.go):
//
//	net_revenue      = 250000 + 300000 + 275000 + 175000 = 1_000_000.00
//	refunds          = 30000 + 20000                     =    50_000.00
//	gross_revenue    = 1_000_000 − 50_000                =   950_000.00
//	total_cogs       = 150000 + 130000 + 100000 + 20000  =   400_000.00
//	gross_margin     = 950_000 − 400_000                 =   550_000.00
//	total_opex       = 80000 + 60000 + 24000 + 18000 + 18000 = 200_000.00
//	operating_income = 550_000 − 200_000                 =   350_000.00
package derivationgraph_test


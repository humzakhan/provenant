// tokenIDs holds the IDs of the key derived tokens produced by the demo.
type tokenIDs struct {
	netRevenue      string
	refunds         string
	grossRevenue    string
	totalCOGS       string
	grossMargin     string
	totalOpex       string
	operatingIncome string
}

// runDemo executes the full derivation-graph CLI sequence and returns the
// IDs of the key derived tokens. The bundlePath must be a non-existent file
// in a writable directory.
func runDemo(t *testing.T, runner cli.Runner, bundlePath string) tokenIDs {
	t.Helper()

	// 1. run start
	testsupport.RunCLIInTest(t, runner, []string{"run", "start", "--request", "-"}, map[string]any{
		"run":      demoRun,
		"run_file": bundlePath,
	})

	// 2. Mint revenue rows (6 rows).
	revenueTokenIDs := mintCSVRowTokens(t, runner, bundlePath, "revenue.csv", 6)

	// 3. Mint COGS rows (4 rows).
	cogsTokenIDs := mintCSVRowTokens(t, runner, bundlePath, "cogs.csv", 4)

	// 4. Mint OpEx rows (5 rows).
	opexTokenIDs := mintCSVRowTokens(t, runner, bundlePath, "opex.csv", 5)

	// 5. filter.sum_where: net_revenue = sum(revenue rows where account == "Revenue")
	netRevenueID := calcFilterSumWhere(t, runner, bundlePath, revenueTokenIDs, "row.account", "eq", "Revenue")

	// 6. filter.sum_where: refunds = sum(revenue rows where account == "Refunds")
	refundsID := calcFilterSumWhere(t, runner, bundlePath, revenueTokenIDs, "row.account", "eq", "Refunds")

	// 7. calc.subtract: gross_revenue = net_revenue - refunds
	grossRevenueID := calcSubtract(t, runner, bundlePath, netRevenueID, refundsID)

	// 8. calc.sum: total_cogs = sum(all cogs rows)
	totalCOGSID := calcSum(t, runner, bundlePath, cogsTokenIDs)

	// 9. calc.sum: total_opex = sum(all opex rows)
	totalOpexID := calcSum(t, runner, bundlePath, opexTokenIDs)

	// 10. calc.subtract: gross_margin = gross_revenue - total_cogs
	grossMarginID := calcSubtract(t, runner, bundlePath, grossRevenueID, totalCOGSID)

	// 11. calc.subtract: operating_income = gross_margin - total_opex
	operatingIncomeID := calcSubtract(t, runner, bundlePath, grossMarginID, totalOpexID)

	// 12. submit-answer: label the operating_income token.
	testsupport.RunCLIInTest(t, runner, []string{"submit-answer", "--request", "-"}, map[string]any{
		"run_file": bundlePath,
		"token_id": operatingIncomeID,
		"label":    "operating_income",
	})

	// 13. run finish
	testsupport.RunCLIInTest(t, runner, []string{"run", "finish", "--request", "-"}, map[string]any{
		"run_file": bundlePath,
	})

	return tokenIDs{
		netRevenue:      netRevenueID,
		refunds:         refundsID,
		grossRevenue:    grossRevenueID,
		totalCOGS:       totalCOGSID,
		grossMargin:     grossMarginID,
		totalOpex:       totalOpexID,
		operatingIncome: operatingIncomeID,
	}
}

// mintCSVRowTokens mints one token per data row from the given CSV file.
// The CSV file must have a header row followed by rowCount data rows.
// The CSV schema is: account,amount.
// Returns the token IDs in row order.
func mintCSVRowTokens(t *testing.T, runner cli.Runner, bundlePath, filename string, rowCount int) []string {
	t.Helper()

	path := filepath.Join(dataDir, filename)
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("ReadFile(%s): %v", path, err)
	}
	src := testsupport.SourceWithHash("fixture://"+filename, data)
	return testsupport.MintCSVRowTokens(t, runner, bundlePath, src, demoRun, rowCount, "", csvAmountOutputPath)
}

// calcFilterSumWhere calls filter.sum_where on the given input IDs.
func calcFilterSumWhere(t *testing.T, runner cli.Runner, bundlePath string, inputs []string, field, op, value string) string {
	t.Helper()
	out := testsupport.RunCLIInTest(t, runner, []string{"calc", "--request", "-"}, map[string]any{
		"run_file": bundlePath,
		"op":       "filter.sum_where",
		"inputs":   inputs,
		"predicate": kernel.RowPredicate{
			Field: field,
			Op:    op,
			Value: value,
		},
	})
	return testsupport.ExtractTokenID(t, out)
}

// calcSubtract calls calc.subtract(a, b) and returns the derived token ID.
func calcSubtract(t *testing.T, runner cli.Runner, bundlePath, aID, bID string) string {
	t.Helper()
	return testsupport.CalcSubtract(t, runner, bundlePath, aID, bID)
}

// calcSum calls calc.sum on the given input IDs.
func calcSum(t *testing.T, runner cli.Runner, bundlePath string, inputs []string) string {
	t.Helper()
	return testsupport.CalcSum(t, runner, bundlePath, inputs)
}

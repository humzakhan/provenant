// fixedDemoTime is the deterministic clock used for all CLI invocations.
var fixedDemoTime = time.Date(2026, 1, 15, 9, 0, 0, 0, time.UTC)

// demoRun is the fixed run identity for the demo.
var demoRun = kernel.Run{
	ID:       "derivation_graph_demo_run_1",
	TenantID: "tenant_demo",
	Status:   kernel.RunRunning,
}

// dataDir is the path to the committed CSV source files.
const dataDir = "data"

// csvOutputPath for the amount column (index 1: account=0, amount=1).
const csvAmountOutputPath = "/rows/0/cells/1/value"

// ---------------------------------------------------------------------------
// TestFauxbooksEndToEnd: full pipeline, golden assertions
// ---------------------------------------------------------------------------

func TestFauxbooksEndToEnd(t *testing.T) {
	dir := t.TempDir()
	bundlePath := filepath.Join(dir, "demo.bundle.json")

	runner := cli.Runner{Now: func() time.Time { return fixedDemoTime }}

	tids := runDemo(t, runner, bundlePath)

	// Assert bundle bytes match golden.
	got, err := os.ReadFile(bundlePath)
	if err != nil {
		t.Fatalf("ReadFile(bundle): %v", err)
	}

	goldenPath := filepath.Join(".", "golden.bundle.json")
	want, readErr := os.ReadFile(goldenPath)
	if readErr != nil {
		// Golden does not exist yet: write it.
		if err2 := os.WriteFile(goldenPath, got, 0o644); err2 != nil {
			t.Fatalf("write golden.bundle.json: %v", err2)
		}
		t.Logf("golden.bundle.json written (%d bytes); re-run to assert equality", len(got))
		want = got
	}
	if !bytes.Equal(got, want) {
		t.Fatal("bundle bytes diverged from golden.bundle.json — if intentional, delete the golden and re-run")
	}

	// Assert bundle.Verify.
	if err := bundle.Verify(got); err != nil {
		t.Fatalf("bundle.Verify: %v", err)
	}

	// Assert bundle.Replay.
	state, err := bundle.Replay(got)
	if err != nil {
		t.Fatalf("bundle.Replay: %v", err)
	}

	// Leaf count: 15 minted tokens (6 revenue + 4 cogs + 5 opex).
	wantLeafCount := 15
	leafCount := 0
	for _, tok := range state.Tokens {
		if tok.Derivation == nil {
			leafCount++
		}
	}
	if leafCount != wantLeafCount {
		t.Errorf("leaf token count = %d, want %d", leafCount, wantLeafCount)
	}

	// Trace operating_income and assert golden trace.
	g, err := trace.Trace(got, tids.operatingIncome)
	if err != nil {
		t.Fatalf("trace.Trace: %v", err)
	}

	raw, err := json.Marshal(g)
	if err != nil {
		t.Fatalf("json.Marshal(graph): %v", err)
	}
	canonical, err := jcs.Transform(raw)
	if err != nil {
		t.Fatalf("jcs.Transform(graph): %v", err)
	}
	canonical = append(canonical, '\n')

	goldenTracePath := filepath.Join(".", "golden.trace.json")
	wantTrace, readTraceErr := os.ReadFile(goldenTracePath)
	if readTraceErr != nil {
		if err2 := os.WriteFile(goldenTracePath, canonical, 0o644); err2 != nil {
			t.Fatalf("write golden.trace.json: %v", err2)
		}
		t.Logf("golden.trace.json written (%d bytes); re-run to assert equality", len(canonical))
		wantTrace = canonical
	}
	if !bytes.Equal(canonical, wantTrace) {
		t.Fatal("trace JSON diverged from golden.trace.json — if intentional, delete the golden and re-run")
	}

	// Contribution invariant: sum(leaf contributions) == operating_income value.
	opIncomeValue := ""
	for _, tok := range state.Tokens {
		if tok.ID == tids.operatingIncome {
			opIncomeValue = tok.ValueCanonical
			break
		}
	}
	if opIncomeValue == "" {
		t.Fatal("operating_income token not found in replayed state")
	}

	sum := decimal.Zero
	for _, lc := range g.Leaves {
		c, err := decimal.NewFromString(lc.Contribution)
		if err != nil {
			t.Fatalf("parse leaf contribution %q: %v", lc.Contribution, err)
		}
		sum = sum.Add(c)
	}
	opIncomeDec, err := decimal.NewFromString(opIncomeValue)
	if err != nil {
		t.Fatalf("parse operating_income value %q: %v", opIncomeValue, err)
	}
	if !sum.Equal(opIncomeDec) {
		t.Errorf("sum(contributions) = %s, want %s", sum.String(), opIncomeValue)
	}

	// Print the leaf contribution table (visible proof of the whole feature).
	t.Logf("Operating Income leaf contribution table:")
	t.Logf("%-48s  %-12s  %s", "source_path", "leaf_value", "contribution")
	t.Logf("%s", strings.Repeat("-", 80))
	for _, lc := range g.Leaves {
		t.Logf("%-48s  %-12s  %s", lc.SourcePath, lc.LeafValue, lc.Contribution)
	}
	t.Logf("%s", strings.Repeat("-", 80))
	t.Logf("%-48s  %-12s  %s", "TOTAL", "", sum.String())
}

// ---------------------------------------------------------------------------
// TestFauxbooksOperatingIncomeValue: spot-check computed value
// ---------------------------------------------------------------------------

func TestFauxbooksOperatingIncomeValue(t *testing.T) {
	// Expected:
	//   net_revenue      = 1_000_000.00
	//   refunds          =    50_000.00
	//   gross_revenue    =   950_000.00
	//   total_cogs       =   400_000.00
	//   gross_margin     =   550_000.00
	//   total_opex       =   200_000.00
	//   operating_income =   350_000.00
	wantOperatingIncome := "350000.000000000"

	dir := t.TempDir()
	bundlePath := filepath.Join(dir, "oi.bundle.json")
	runner := cli.Runner{Now: func() time.Time { return fixedDemoTime }}

	tids := runDemo(t, runner, bundlePath)

	got, err := os.ReadFile(bundlePath)
	if err != nil {
		t.Fatalf("ReadFile(bundle): %v", err)
	}

	state, err := bundle.Replay(got)
	if err != nil {
		t.Fatalf("bundle.Replay: %v", err)
	}

	var opIncome string
	for _, tok := range state.Tokens {
		if tok.ID == tids.operatingIncome {
			opIncome = tok.ValueCanonical
			break
		}
	}
	if opIncome == "" {
		t.Fatal("operating_income token not found")
	}
	if opIncome != wantOperatingIncome {
		t.Errorf("operating_income = %q, want %q", opIncome, wantOperatingIncome)
	}
}

// ---------------------------------------------------------------------------
// TestFauxbooksTraceLeafCount: trace decomposes into exactly 15 leaves
// ---------------------------------------------------------------------------

func TestFauxbooksTraceLeafCount(t *testing.T) {
	// Leaf count breakdown:
	//   net_revenue (filter.sum_where on 6 revenue rows) → 6 leaves
	//   refunds     (filter.sum_where on 6 revenue rows) → 6 leaves
	//   total_cogs  (calc.sum on 4 cogs rows)            → 4 leaves
	//   total_opex  (calc.sum on 5 opex rows)            → 5 leaves
	// Total: 21 leaf entries (revenue rows appear twice — once in net_revenue,
	// once in refunds — because filter.sum_where includes all 6 rows each time,
	// with 0-contribution for the non-matching side).
	dir := t.TempDir()
	bundlePath := filepath.Join(dir, "lc.bundle.json")
	runner := cli.Runner{Now: func() time.Time { return fixedDemoTime }}

	tids := runDemo(t, runner, bundlePath)

	got, err := os.ReadFile(bundlePath)
	if err != nil {
		t.Fatalf("ReadFile(bundle): %v", err)
	}

	g, err := trace.Trace(got, tids.operatingIncome)
	if err != nil {
		t.Fatalf("trace.Trace: %v", err)
	}

	// 6+6+4+5 = 21 total leaf contribution entries.
	wantLeafCount := 21
	if lc := len(g.Leaves); lc != wantLeafCount {
		t.Errorf("leaf count = %d, want %d", lc, wantLeafCount)
	}
}

// ---------------------------------------------------------------------------
// TestFauxbooksReplayDeterminism: two runs produce identical bundle bytes
// ---------------------------------------------------------------------------

func TestFauxbooksReplayDeterminism(t *testing.T) {
	makeBundle := func(t *testing.T) []byte {
		t.Helper()
		dir := t.TempDir()
		bundlePath := filepath.Join(dir, "det.bundle.json")
		runner := cli.Runner{Now: func() time.Time { return fixedDemoTime }}
		runDemo(t, runner, bundlePath)
		data, err := os.ReadFile(bundlePath)
		if err != nil {
			t.Fatalf("ReadFile(bundle): %v", err)
		}
		return data
	}

	b1 := makeBundle(t)
	b2 := makeBundle(t)
	if !bytes.Equal(b1, b2) {
		t.Fatal("two independent runs produced different bundle bytes — non-determinism bug")
	}
}

